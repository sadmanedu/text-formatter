function loadSample() {
    const input = document.getElementById('input');
    if (!input) return;
    input.value = sampleText;
    updateCharCount();
    reformat();
    showToast('📄 Sample text loaded!');
    input.focus();
}

function clearAll() {
    const input = document.getElementById('input');
    const preview = document.getElementById('preview');
    if (input) input.value = '';
    if (preview) preview.innerHTML = `<p style="color:#888; font-style:italic;">Formatted preview will appear here...<br>ফরম্যাটেড লেখা এখানে দেখা যাবে...</p>`;
    updateCharCount();
    showToast('🗑️ Cleared!');
}

function insertAtCursor(before, after) {
    const input = document.getElementById('input');
    if (!input) return;
    const start = input.selectionStart;
    const end = input.selectionEnd;
    const selected = input.value.substring(start, end);
    const newText = before + selected + after;
    input.value = input.value.substring(0, start) + newText + input.value.substring(end);
    input.focus();
    input.setSelectionRange(start + before.length, start + before.length + selected.length);
    updateCharCount();
    reformat();
}

function showToast(message) {
    const toast = document.getElementById('toast');
    if (!toast) return;
    toast.textContent = message;
    toast.classList.add('show');
    setTimeout(() => {
        toast.classList.remove('show');
    }, 3500);
}


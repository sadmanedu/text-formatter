// --- Core Parser ---
function escapeHtml(str) {
    return str
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;');
}

function parseInline(text, opts) {
    let s = escapeHtml(text);

    // Inline code `code`
    s = s.replace(/`([^`]+?)`/g, (m, p1) => {
        return `<code style="font-family:'Courier New', monospace; background:#f1f5f9; padding:1pt 4pt; border:1px solid #e2e8f0; border-radius:3pt; font-size:10.5pt;">${p1}</code>`;
    });

    // Bold **text**
    s = s.replace(/\*\*([\s\S]+?)\*\*/g, (m, p1) => {
        return `<strong style="font-weight:700;">${p1}</strong>`;
    });

    // Underline __text__ (custom for this formatter)
    s = s.replace(/__([\s\S]+?)__/g, (m, p1) => {
        // Avoid if it's part of ___ hr, but inline context safe
        if (p1.trim() === '' ) return m;
        return `<u style="text-decoration:underline; text-underline-offset:2pt;">${p1}</u>`;
    });

    // Italic *text*  (single star, not double)
    // Use negative lookbehind/ahead to avoid **, but fallback for older browsers
    try {
        s = s.replace(/(?<!\*)\*([^\*\n]+?)\*(?!\*)/g, (m, p1) => {
            return `<em style="font-style:italic;">${p1}</em>`;
        });
    } catch (e) {
        // fallback without lookbehind
        s = s.replace(/\*([^\*\n]+?)\*/g, (m, p1) => {
            // avoid if contains ** inside? already replaced
            if (p1.includes('*')) return m;
            return `<em style="font-style:italic;">${p1}</em>`;
        });
    }

    // Italic _text_  (underscore, but not __)
    try {
        s = s.replace(/(?<!_)_(?!_)([^_\n]+?)(?<!_)_(?!_)/g, (m, p1) => {
            return `<em style="font-style:italic;">${p1}</em>`;
        });
    } catch (e) {
        // ignore
    }

    // Strikethrough ~~text~~
    s = s.replace(/~~([\s\S]+?)~~/g, '<span style="text-decoration:line-through;">$1</span>');

    // Highlight ==text== -> yellow background (useful for Word)
    s = s.replace(/==([\s\S]+?)==/g, '<span style="background:#fef08a; padding:1pt 2pt;">$1</span>');

    // Links [text](url)
    s = s.replace(/\[([^\]]+?)\]\((https?:\/\/[^\s)]+)\)/g, (m, p1, p2) => {
        return `<a href="${p2}" style="color:#2563eb; text-decoration:underline;">${p1}</a>`;
    });

    // Auto-link URLs
    s = s.replace(/(https?:\/\/[^\s<]+)/g, (m) => {
        if (m.includes('href=')) return m;
        return `<a href="${m}" style="color:#2563eb; text-decoration:underline;">${m}</a>`;
    });

    return s;
}

function parseMarkdownToHTML(markdown, opts) {
    const fontFamily = opts.fontFamily;
    const baseSize = opts.baseSize;
    const lineHeight = opts.lineHeight;

    // Extract code blocks ```...```
    const codeBlocks = [];
    let md = markdown.replace(/```([\s\S]*?)```/g, (match, p1) => {
        // Remove first line if it's language identifier
        let content = p1;
        // If first line is like "js" or similar and no spaces, remove
        const lines = content.split('\n');
        if (lines.length > 1 && /^[a-zA-Z0-9_+-]+$/.test(lines[0].trim()) && lines[0].trim().length < 15) {
            content = lines.slice(1).join('\n');
        }
        const placeholder = `__CODEBLOCK_${codeBlocks.length}__`;
        codeBlocks.push(content);
        return placeholder;
    });

    const lines = md.split('\n');
    let html = '';
    let paragraphBuffer = [];

    // List stack: {type: 'ul'|'ol', indent: number, openLi: boolean}
    let listStack = [];

    // Table buffer
    let tableBuffer = null; // {headerLine, sepLine, rows: []}

    function flushParagraph() {
        if (paragraphBuffer.length > 0) {
            const raw = paragraphBuffer.join(' ').trim();
            if (raw) {
                // Check for codeblock placeholder alone
                const codeMatch = raw.match(/^__CODEBLOCK_(\d+)__$/);
                if (codeMatch) {
                    const idx = parseInt(codeMatch[1], 10);
                    const codeContent = escapeHtml(codeBlocks[idx] || '');
                    html += `<pre style="font-family:'Courier New', monospace; background:#f8fafc; border:1px solid #e2e8f0; padding:12pt; white-space:pre-wrap; font-size:10.5pt; line-height:1.5; margin:10pt 0; border-radius:6px; font-family:'Courier New', monospace;">${codeContent}</pre>`;
                } else {
                    // Check if raw contains only codeblock placeholders mixed? handle
                    let processed = raw;
                    // Replace any codeblock placeholders inside paragraph? Should be separate but handle
                    processed = processed.replace(/__CODEBLOCK_(\d+)__/g, (m, idx) => {
                        const codeContent = escapeHtml(codeBlocks[parseInt(idx)] || '');
                        return `</p><pre style="font-family:'Courier New', monospace; background:#f8fafc; border:1px solid #e2e8f0; padding:12pt; white-space:pre-wrap; font-size:10.5pt; line-height:1.5; margin:10pt 0; border-radius:6px;">${codeContent}</pre><p style="font-size:${baseSize}pt; line-height:${lineHeight}; margin:6pt 0; font-family:${fontFamily};">`;
                    });
                    // If processed contains </p><pre> we need to split
                    if (processed.includes('</p><pre')) {
                        // close current p and insert
                        const parts = processed.split(/<\/p><pre/);
                        // Actually our replace created broken html, let's handle differently
                        // Simplify: if raw includes placeholder, render each separately
                        const segments = raw.split(/(__CODEBLOCK_\d+__)/g);
                        let tempHtml = '';
                        for (const seg of segments) {
                            const cm = seg.match(/^__CODEBLOCK_(\d+)__$/);
                            if (cm) {
                                const idx = parseInt(cm[1], 10);
                                const codeContent = escapeHtml(codeBlocks[idx] || '');
                                tempHtml += `</p><pre style="font-family:'Courier New', monospace; background:#f8fafc; border:1px solid #e2e8f0; padding:12pt; white-space:pre-wrap; font-size:10.5pt; line-height:1.5; margin:10pt 0; border-radius:6px;">${codeContent}</pre><p style="font-size:${baseSize}pt; line-height:${lineHeight}; margin:6pt 0; font-family:${fontFamily};">`;
                            } else if (seg.trim()) {
                                tempHtml += parseInline(seg.trim(), opts);
                            }
                        }
                        // Wrap
                        html += `<p style="font-size:${baseSize}pt; line-height:${lineHeight}; margin:6pt 0; font-family:${fontFamily};">${tempHtml}</p>`;
                        // Clean empty p tags that may result
                        html = html.replace(/<p[^>]*>\s*<\/p>/g, '');
                        html = html.replace(/<p[^>]*>\s*<\/p><pre/g, '<pre');
                        html = html.replace(/<\/pre><p[^>]*>\s*<\/p>/g, '</pre>');
                    } else {
                        html += `<p style="font-size:${baseSize}pt; line-height:${lineHeight}; margin:6pt 0; font-family:${fontFamily};">${parseInline(raw, opts)}</p>`;
                    }
                }
            }
            paragraphBuffer = [];
        }
    }

    function closeLists(toIndent = -1) {
        while (listStack.length > 0 && listStack[listStack.length - 1].indent > toIndent) {
            const top = listStack.pop();
            if (top.openLi) {
                html += `</li>`;
            }
            html += `</${top.type}>`;
        }
        // If toIndent equals top indent and we need to close li
        if (listStack.length > 0 && toIndent >= 0 && listStack[listStack.length - 1].indent === toIndent) {
            // keep list open but close previous li
            if (listStack[listStack.length - 1].openLi) {
                html += `</li>`;
                listStack[listStack.length - 1].openLi = false;
            }
        }
    }

    function closeAllLists() {
        while (listStack.length > 0) {
            const top = listStack.pop();
            if (top.openLi) html += `</li>`;
            html += `</${top.type}>`;
        }
    }

    function isTableSeparator(line) {
        // matches |---|---| or ---|--- etc
        const trimmed = line.trim();
        if (!trimmed.includes('|') && !trimmed.includes('-')) return false;
        // Must contain at least --- and only | - : space
        return /^[\s|:\-]+$/.test(trimmed) && trimmed.includes('-');
    }

    function parseTableRow(line) {
        // Split by |, trim, remove empty first/last if line starts/ends with |
        let row = line.trim();
        if (row.startsWith('|')) row = row.slice(1);
        if (row.endsWith('|')) row = row.slice(0, -1);
        return row.split('|').map(cell => cell.trim());
    }

    function flushTable() {
        if (tableBuffer && tableBuffer.rows.length > 0) {
            const headerCells = parseTableRow(tableBuffer.headerLine);
            const rows = tableBuffer.rows.map(parseTableRow);

            let tableHtml = `<table style="width:100%; border-collapse:collapse; margin:12pt 0; font-size:${parseInt(baseSize) - 0.5}pt; font-family:${fontFamily}; border:1px solid #000;">`;
            tableHtml += `<thead><tr>`;
            for (const cell of headerCells) {
                tableHtml += `<th style="border:1px solid #000; padding:6pt 8pt; background:#f1f5f9; font-weight:700; text-align:left;">${parseInline(cell, opts)}</th>`;
            }
            tableHtml += `</tr></thead><tbody>`;
            for (const row of rows) {
                tableHtml += `<tr>`;
                for (let i = 0; i < headerCells.length; i++) {
                    const cell = row[i] || '';
                    tableHtml += `<td style="border:1px solid #000; padding:6pt 8pt; text-align:left;">${parseInline(cell, opts)}</td>`;
                }
                tableHtml += `</tr>`;
            }
            tableHtml += `</tbody></table>`;
            html += tableHtml;
        }
        tableBuffer = null;
    }

    for (let i = 0; i < lines.length; i++) {
        let line = lines[i];
        const trimmed = line.trim();

        // Empty line
        if (trimmed === '') {
            flushParagraph();
            // If in table, flush table
            if (tableBuffer) {
                flushTable();
            }
            // Don't close lists on empty line - markdown allows blank lines inside lists? But we will keep lists open
            continue;
        }

        // Check for table start: current line has | and next line is separator
        if (!tableBuffer && trimmed.includes('|') && i + 1 < lines.length && isTableSeparator(lines[i + 1])) {
            flushParagraph();
            closeAllLists();
            tableBuffer = {
                headerLine: line,
                sepLine: lines[i + 1],
                rows: []
            };
            i++; // skip separator line
            continue;
        }

        if (tableBuffer) {
            if (trimmed.includes('|')) {
                tableBuffer.rows.push(line);
                continue;
            } else {
                // End of table
                flushTable();
                // Continue processing this line as normal
            }
        }

        // Codeblock placeholder line alone
        if (/^__CODEBLOCK_\d+__$/.test(trimmed)) {
            flushParagraph();
            closeAllLists();
            const idx = parseInt(trimmed.match(/\d+/)[0], 10);
            const codeContent = escapeHtml(codeBlocks[idx] || '');
            html += `<pre style="font-family:'Courier New', monospace; background:#f8fafc; border:1px solid #e2e8f0; padding:12pt; white-space:pre-wrap; font-size:10.5pt; line-height:1.5; margin:10pt 0; border-radius:6px;">${codeContent}</pre>`;
            continue;
        }

        // Heading
        const headingMatch = line.match(/^(#{1,6})\s+(.*)$/);
        if (headingMatch) {
            flushParagraph();
            closeAllLists();
            const level = headingMatch[1].length;
            const content = headingMatch[2].trim();
            const inlineContent = parseInline(content, opts);

            let style = `font-family:${fontFamily}; margin:14pt 0 6pt 0; line-height:1.3; color:#0f172a;`;
            if (level === 1) {
                style += `font-size:22pt; font-weight:700; border-bottom:2px solid #e2e8f0; padding-bottom:6pt; margin-top:18pt;`;
                html += `<h1 style="${style}">${inlineContent}</h1>`;
            } else if (level === 2) {
                style += `font-size:18pt; font-weight:700; color:#1e293b; margin-top:16pt;`;
                html += `<h2 style="${style}">${inlineContent}</h2>`;
            } else if (level === 3) {
                style += `font-size:14pt; font-weight:700; color:#334155; margin-top:12pt;`;
                html += `<h3 style="${style}">${inlineContent}</h3>`;
            } else if (level === 4) {
                style += `font-size:12pt; font-weight:700; color:#475569; margin-top:10pt;`;
                html += `<h4 style="${style}">${inlineContent}</h4>`;
            } else if (level === 5) {
                style += `font-size:11pt; font-weight:700; color:#64748b; margin-top:8pt;`;
                html += `<h5 style="${style}">${inlineContent}</h5>`;
            } else {
                style += `font-size:10pt; font-weight:700; color:#64748b; margin-top:8pt;`;
                html += `<h6 style="${style}">${inlineContent}</h6>`;
            }
            continue;
        }

        // Horizontal rule
        if (/^\s*([-*_])\s*\1\s*\1(\s*\1)*\s*$/.test(line) && trimmed.length >= 3) {
            flushParagraph();
            closeAllLists();
            if (tableBuffer) flushTable();
            html += `<hr style="border:none; border-top:1.5pt solid #cbd5e1; margin:16pt 0;">`;
            continue;
        }

        // List detection
        // Supports: - * •, numbered 1. 1) and Bengali digits ১. ২) etc
        const listMatch = line.match(/^(\s*)([-*•]|\d+[.)]|[০-৯]+[.)]|[a-zA-Z][.)])\s+(.*)$/);
        if (listMatch) {
            flushParagraph();
            const leadingSpaces = listMatch[1].length;
            const marker = listMatch[2];
            const content = listMatch[3];

            const indent = Math.floor(leadingSpaces / 2); // 2 spaces per level
            const isOrdered = /^\d+[.)]$/.test(marker) || /^[০-৯]+[.)]$/.test(marker) || /^[a-zA-Z][.)]$/.test(marker);
            const listType = isOrdered ? 'ol' : 'ul';

            // Manage stack
            if (listStack.length === 0) {
                // Open new list
                const listStyle = listType === 'ul'
                    ? `margin:8pt 0 8pt 24pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight}; list-style-type:disc;`
                    : `margin:8pt 0 8pt 24pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight};`;
                html += `<${listType} style="${listStyle}">`;
                listStack.push({ type: listType, indent: indent, openLi: false });
            } else {
                const top = listStack[listStack.length - 1];
                if (indent > top.indent) {
                    // Nested list
                    const listStyle = listType === 'ul'
                        ? `margin:4pt 0 4pt 16pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight}; list-style-type:circle;`
                        : `margin:4pt 0 4pt 16pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight};`;
                    html += `<${listType} style="${listStyle}">`;
                    listStack.push({ type: listType, indent: indent, openLi: false });
                } else if (indent < top.indent) {
                    // Close deeper lists
                    while (listStack.length > 0 && listStack[listStack.length - 1].indent > indent) {
                        const t = listStack.pop();
                        if (t.openLi) html += `</li>`;
                        html += `</${t.type}>`;
                    }
                    // Check type at current indent
                    if (listStack.length > 0) {
                        const curTop = listStack[listStack.length - 1];
                        if (curTop.indent === indent && curTop.type !== listType) {
                            // Close and reopen with new type
                            if (curTop.openLi) html += `</li>`;
                            html += `</${curTop.type}>`;
                            listStack.pop();
                            const listStyle = listType === 'ul'
                                ? `margin:8pt 0 8pt 24pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight}; list-style-type:disc;`
                                : `margin:8pt 0 8pt 24pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight};`;
                            html += `<${listType} style="${listStyle}">`;
                            listStack.push({ type: listType, indent: indent, openLi: false });
                        } else if (curTop.indent === indent && curTop.openLi) {
                            html += `</li>`;
                            curTop.openLi = false;
                        } else if (curTop.indent < indent) {
                            // Should not happen after while, but handle
                            const listStyle = listType === 'ul'
                                ? `margin:4pt 0 4pt 16pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight};`
                                : `margin:4pt 0 4pt 16pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight};`;
                            html += `<${listType} style="${listStyle}">`;
                            listStack.push({ type: listType, indent: indent, openLi: false });
                        }
                    } else {
                        // Stack empty after closing
                        const listStyle = listType === 'ul'
                            ? `margin:8pt 0 8pt 24pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight}; list-style-type:disc;`
                            : `margin:8pt 0 8pt 24pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight};`;
                        html += `<${listType} style="${listStyle}">`;
                        listStack.push({ type: listType, indent: indent, openLi: false });
                    }
                } else {
                    // Same indent
                    const curTop = listStack[listStack.length - 1];
                    if (curTop.type !== listType) {
                        if (curTop.openLi) html += `</li>`;
                        html += `</${curTop.type}>`;
                        listStack.pop();
                        const listStyle = listType === 'ul'
                            ? `margin:8pt 0 8pt 24pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight};`
                            : `margin:8pt 0 8pt 24pt; padding-left:12pt; font-family:${fontFamily}; font-size:${baseSize}pt; line-height:${lineHeight};`;
                        html += `<${listType} style="${listStyle}">`;
                        listStack.push({ type: listType, indent: indent, openLi: false });
                    } else {
                        if (curTop.openLi) {
                            html += `</li>`;
                            curTop.openLi = false;
                        }
                    }
                }
            }

            // Now open li
            const currentList = listStack[listStack.length - 1];
            html += `<li style="margin:3pt 0; font-size:${baseSize}pt; line-height:${lineHeight}; font-family:${fontFamily};">${parseInline(content, opts)}`;
            currentList.openLi = true;
            continue;
        }

        // If not list, but we have open lists and this line is not indented, close lists?
        // Check if line is not indented and not empty, then close lists
        if (listStack.length > 0 && !/^\s/.test(line)) {
            // Only close if this is not a continuation of list item (paragraph inside list)
            // For simplicity, close all lists when encountering non-list, non-indented line
            // But if next line is list, we already handled. So close here for paragraph.
            // We'll close after flushing? Actually we should keep list open for multi-line list items?
            // Let's check: if line is indented by 2+ spaces and previous was list, treat as continuation
            // Otherwise close.
            const isContinuation = /^\s{2,}\S/.test(line) && listStack.length > 0;
            if (!isContinuation) {
                // Close all lists before paragraph
                // But we will flush paragraph later, so close now
                closeAllLists();
            } else {
                // Continuation of previous li: add to same li with <br>
                if (listStack.length > 0) {
                    const top = listStack[listStack.length - 1];
                    if (top.openLi) {
                        html += `<br>${parseInline(trimmed, opts)}`;
                        continue;
                    }
                }
            }
        }

        // Normal paragraph line
        paragraphBuffer.push(line.trim());
    }

    // End of file: flush remaining
    flushParagraph();
    if (tableBuffer) flushTable();
    closeAllLists();

    // Clean up empty p tags
    html = html.replace(/<p[^>]*>\s*<\/p>/g, '');

    return html;
}

// --- Clipboard & Download ---

async function copyFormatted() {
    const preview = document.getElementById('preview');
    if (!preview) return;

    const htmlContent = preview.innerHTML;
    const plainText = preview.innerText;

    // Create a full HTML doc for Word compatibility
    const opts = getOptions();
    const fullHtmlForWord = `<!DOCTYPE html><html><head><meta charset="UTF-8"><style>body{font-family:${opts.fontFamily}; font-size:${opts.baseSize}pt; line-height:${opts.lineHeight};}</style></head><body>${htmlContent}</body></html>`;

    try {
        if (navigator.clipboard && window.ClipboardItem) {
            const htmlBlob = new Blob([fullHtmlForWord], { type: 'text/html' });
            const textBlob = new Blob([plainText], { type: 'text/plain' });
            const data = [new ClipboardItem({ 'text/html': htmlBlob, 'text/plain': textBlob })];
            await navigator.clipboard.write(data);
            showToast('✅ Formatted text copied! Now paste into MS Word with Ctrl+V');
        } else {
            // Fallback: select and copy
            fallbackCopy(preview);
        }
    } catch (e) {
        console.error('Clipboard API failed', e);
        fallbackCopy(preview);
    }
}

function fallbackCopy(element) {
    const range = document.createRange();
    range.selectNodeContents(element);
    const sel = window.getSelection();
    sel.removeAllRanges();
    sel.addRange(range);
    try {
        const successful = document.execCommand('copy');
        if (successful) {
            showToast('✅ Copied! Paste into Word (Ctrl+V). Use Keep Source Formatting if prompted.');
        } else {
            showToast('⚠️ Copy failed. Please select all (Ctrl+A) and copy manually.');
        }
    } catch (err) {
        showToast('⚠️ Please manually select all (Ctrl+A) in preview and copy.');
    }
    sel.removeAllRanges();
}

function copyHTML() {
    const preview = document.getElementById('preview');
    if (!preview) return;
    const html = preview.innerHTML;
    navigator.clipboard.writeText(html).then(() => {
        showToast('📄 HTML code copied to clipboard!');
    }).catch(() => {
        // fallback
        const ta = document.createElement('textarea');
        ta.value = html;
        document.body.appendChild(ta);
        ta.select();
        document.execCommand('copy');
        document.body.removeChild(ta);
        showToast('📄 HTML copied!');
    });
}

function downloadAsDoc() {
    const preview = document.getElementById('preview');
    if (!preview) return;
    const opts = getOptions();
    const htmlContent = preview.innerHTML;

    // Word-compatible HTML with header
    const wordHtml = `
<html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
<head>
<meta charset="UTF-8">
<meta name="ProgId" content="Word.Document">
<meta name="Generator" content="Microsoft Word 15">
<meta name="Originator" content="Microsoft Word 15">
<style>
@page { margin: 1in; }
body { font-family: ${opts.fontFamily}; font-size: ${opts.baseSize}pt; line-height: ${opts.lineHeight}; }
table { border-collapse: collapse; }
td, th { border: 1px solid #000; }
</style>
</head>
<body>
${htmlContent}
</body>
</html>`;

    const blob = new Blob([wordHtml], { type: 'application/msword' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'formatted-document.doc';
    document.body.appendChild(a);
    a.click();
    setTimeout(() => {
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
    }, 100);
    showToast('⬇️ Word .doc downloaded!');
}

